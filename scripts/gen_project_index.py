"""Generate the project-wide `index.org` listing every course by domain.

Each course row shows its slug, the counts of lectures / assignments /
supplementary pages inside `org-latex/`, and which directories are present.
The output is overwritten on every run — do not hand-edit.
"""
from __future__ import annotations

import argparse
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Iterable

_TITLE_RE = re.compile(r"^#\+title:\s*(.+)$", re.MULTILINE | re.IGNORECASE)
_SHORT_RE = re.compile(r"\*\s*Short code:\*\s*=([a-z][a-z0-9-]*)=")
_LICENCE_RE = re.compile(r"\*\s*(?:Wiki )?[Ll]icen[cs]e:\*\s*(.+)")


@dataclass
class CourseEntry:
    domain: str
    slug: str
    title: str
    short: str | None
    licence: str | None
    lectures: int
    assignments: int
    supplementary: int
    has_source: bool
    has_markdown: bool
    has_org_latex: bool
    has_org_typst: bool


def _read_meta(course_dir: Path) -> tuple[str | None, str | None, str | None]:
    readme = course_dir / "README.org"
    if not readme.exists():
        return None, None, None
    text = readme.read_text(encoding="utf-8", errors="replace")
    tm = _TITLE_RE.search(text)
    sm = _SHORT_RE.search(text)
    lm = _LICENCE_RE.search(text)
    title = tm.group(1).strip() if tm else None
    short = sm.group(1) if sm else None
    licence = lm.group(1).strip() if lm else None
    return title, short, licence


def _count_pages(org_dir: Path, subdir: str) -> int:
    d = org_dir / subdir
    if not d.is_dir():
        return 0
    return sum(1 for _ in d.glob("*.org"))


def _humanize_slug(slug: str) -> str:
    return " ".join(w.capitalize() for w in slug.split("-"))


def iter_courses(root: Path) -> Iterable[CourseEntry]:
    for domain in sorted(root.iterdir()):
        if not domain.is_dir() or domain.name.startswith("."):
            continue
        if domain.name in {"protocol", "scripts", "_incoming"}:
            continue
        for course in sorted(domain.iterdir()):
            if not course.is_dir():
                continue
            if not any(
                (course / sub).is_dir()
                for sub in ("source", "markdown", "org-latex", "org-typst")
            ):
                continue
            title, short, licence = _read_meta(course)
            if title is None:
                title = _humanize_slug(course.name)
            org_latex = course / "org-latex"
            org_typst = course / "org-typst"
            yield CourseEntry(
                domain=domain.name,
                slug=course.name,
                title=title,
                short=short,
                licence=licence,
                lectures=_count_pages(org_latex, "lectures"),
                assignments=_count_pages(org_latex, "assignments"),
                supplementary=_count_pages(org_latex, "supplementary"),
                has_source=(course / "source").is_dir(),
                has_markdown=(course / "markdown").is_dir(),
                has_org_latex=org_latex.is_dir(),
                has_org_typst=org_typst.is_dir(),
            )


def render(entries: list[CourseEntry]) -> str:
    out: list[str] = [
        "#+title: Lecture notes wiki — index",
        "#+startup: overview",
        "",
        "Every course in the wiki, grouped by domain. Generated by",
        "=scripts/gen_project_index.py=; do not hand-edit. Re-run after",
        "any conversion to refresh.",
        "",
        "The *Status* column names which subdirs are present; the counts",
        "are the number of files inside =org-latex/{lectures,assignments,",
        "supplementary}/=. Rows with no =org-latex/= still need LaTeX",
        "conversion. See =courses.org= for licence tracking.",
        "",
    ]

    by_domain: dict[str, list[CourseEntry]] = {}
    for e in entries:
        by_domain.setdefault(e.domain, []).append(e)

    totals = {
        "courses": len(entries),
        "with_org_latex": sum(1 for e in entries if e.has_org_latex),
        "lectures": sum(e.lectures for e in entries),
        "assignments": sum(e.assignments for e in entries),
        "supplementary": sum(e.supplementary for e in entries),
    }
    out.append("* Totals")
    out.append("")
    out.append(f"- Courses: {totals['courses']}")
    out.append(f"- Converted to =org-latex/=: {totals['with_org_latex']}")
    out.append(f"- Lecture files: {totals['lectures']}")
    out.append(f"- Assignment files: {totals['assignments']}")
    out.append(f"- Supplementary files: {totals['supplementary']}")
    out.append("")

    for domain in sorted(by_domain):
        out.append(f"* {domain.capitalize()}")
        out.append("")
        out.append("| Slug | Title | Lectures | Assignments | Supp. | Status |")
        out.append("|------+-------+----------+-------------+-------+--------|")
        for e in by_domain[domain]:
            status = _status_tag(e)
            lect = e.lectures or "—"
            asgn = e.assignments or "—"
            supp = e.supplementary or "—"
            index_link = (
                f"[[file:{e.domain}/{e.slug}/org-latex/index.org][{e.slug}]]"
                if e.has_org_latex
                else f"={e.slug}="
            )
            out.append(
                f"| {index_link} | {e.title} | {lect} | {asgn} | {supp} | {status} |"
            )
        out.append("")

    unconverted = [e for e in entries if not e.has_org_latex]
    if unconverted:
        out.append("* Pending conversion")
        out.append("")
        for e in unconverted:
            parts = []
            if e.has_source:
                parts.append("source/")
            if e.has_markdown:
                parts.append("markdown/")
            if e.has_org_typst:
                parts.append("org-typst/")
            parts_s = "+".join(parts) or "(no upstream)"
            out.append(f"- =~/{e.domain}/{e.slug}= [{parts_s}]")
        out.append("")

    return "\n".join(out)


def _status_tag(e: CourseEntry) -> str:
    parts = []
    if e.has_source:
        parts.append("source")
    if e.has_markdown:
        parts.append("markdown")
    if e.has_org_latex:
        parts.append("org-latex")
    if e.has_org_typst:
        parts.append("org-typst")
    return "+".join(parts) or "—"


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python3 -m scripts.gen_project_index")
    p.add_argument("--root", type=Path, default=Path("."),
                   help="Project root (default: cwd).")
    p.add_argument("--out", type=Path, default=None,
                   help="Output file (default: <root>/index.org).")
    args = p.parse_args(argv)

    root = args.root.resolve()
    out_path = args.out or (root / "index.org")

    entries = list(iter_courses(root))
    text = render(entries)
    out_path.write_text(text, encoding="utf-8")
    print(f"wrote {out_path} ({len(entries)} courses)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
