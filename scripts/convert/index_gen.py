"""Generate the per-course index.org. Protocol K1."""
from __future__ import annotations

from .model import CourseMeta, Page, PageKind
from .slug import format_assignment_filename, format_lecture_filename


def build(meta: CourseMeta, pages: list[Page]) -> str:
    """Return the full text of org-mode/index.org.

    Lectures and assignments are listed in NUMBER order (so sf-05 before
    sf-06 even when the upstream SUMMARY swaps them). Supplementary pages
    stay in parsed order (TOC order).
    """
    lectures = sorted(
        (p for p in pages if p.kind in (PageKind.LECTURE, PageKind.OWN_NOTES)),
        key=lambda p: p.number,
    )
    assignments = sorted(
        (p for p in pages if p.kind == PageKind.ASSIGNMENT),
        key=lambda p: p.number,
    )
    supplementary = [p for p in pages if p.kind == PageKind.SUPPLEMENTARY]

    out: list[str] = [
        f"#+title: {meta.name} — index",
        "#+startup: overview",
        "",
        "Generated by =scripts/convert/=. Do not hand-edit; the generator",
        "overwrites this file every run.",
        "",
    ]

    if lectures:
        out.append("* Lectures")
        out.append("")
        for p in lectures:
            filename = format_lecture_filename(meta.short, p.number, p.slug)
            out.append(f"+ [[file:lectures/{filename}][{p.number} {p.title}]]")
        out.append("")

    if assignments:
        out.append("* Assignments")
        out.append("")
        for p in assignments:
            filename = format_assignment_filename(meta.short, p.number)
            out.append(f"+ [[file:assignments/{filename}][{p.number} assignment]]")
        out.append("")

    if supplementary:
        out.append("* Supplementary")
        out.append("")
        for p in supplementary:
            filename = f"supp-{p.slug}.org"
            out.append(f"+ [[file:supplementary/{filename}][{p.title}]]")
        out.append("")

    return "\n".join(out)
